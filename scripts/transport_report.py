def report_markdown(root: Path = REPO) -> str:
    """The generated block: the eight comparison tables, each with its source paragraph.

    Reads only the files in SOURCES below root. Raises ValueError naming the file when one is
    missing, is not valid JSON, or lacks a field a table needs.
    """
    data = read_sources(Path(root))
    sections = []
    for build, files in TABLES:
        try:
            sections.append(build(data))
        except (AttributeError, IndexError, KeyError, StopIteration, TypeError,
                ValueError) as error:
            raise ValueError(f"unexpected content in {', '.join(files)}: {error!r}") from None
    return "\n\n".join(sections) + "\n"


# --- The document ------------------------------------------------------------------------------


def split_doc(text: str, name: str) -> tuple[str, str, str]:
    """The text through the BEGIN_MARKER line, the generated block, and the END_MARKER line on.

    Raises ValueError unless there is exactly one BEGIN_MARKER line and, after it, exactly one
    END_MARKER line.
    """
    lines = text.splitlines(keepends=True)
    begins = [index for index, line in enumerate(lines) if line.rstrip("\r\n") == BEGIN_MARKER]
    ends = [index for index, line in enumerate(lines) if line.rstrip("\r\n") == END_MARKER]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise ValueError(f"{name} needs exactly one line {BEGIN_MARKER} followed later by "
                         f"exactly one line {END_MARKER}")
    begin, end = begins[0], ends[0]
    return "".join(lines[:begin + 1]), "".join(lines[begin + 1:end]), "".join(lines[end:])


def read_doc(path: Path) -> str:
    """The document's text, byte for byte."""
    try:
        return path.read_bytes().decode("utf-8")
    except OSError as error:
        raise ValueError(f"cannot read {path}: {error.strerror or error}") from None
    except UnicodeDecodeError as error:
        raise ValueError(f"{path} is not UTF-8: {error}") from None


def main(argv: Sequence[str] | None = None) -> int:
    """Print the generated block, or --check or --write it in the document.

    Returns 0 on success, 1 when --check finds the block out of date or a source or the
    document cannot be read, and leaves argparse to exit 2 on a usage error.
    """
    parser =argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="exit 1 if the document's generated block is out of date")
    mode.add_argument("--write", action="store_true",
                      help="replace the document's generated block, leaving the rest unchanged")
    parser.add_argument("--doc", type=Path, default=DOC,
                        help="the document with the marker lines (default: RECOMMENDATIONS.md)")
    args = parser.parse_args(argv)

    try:
        if not (args.check or args.write):
            sys.stdout.write(report_markdown(REPO))
            return 0
        # Both the document and the sources are read before anything is written.
        head, block, tail = split_doc(read_doc(args.doc), str(args.doc))
        report = report_markdown(REPO)
        if args.check:
            if block != report:
                print(f"{args.doc} is out of date: its generated block differs from the "
                      "committed results; run scripts/transport_report.py --write",
                      file=sys.stderr)
                return 1
            return 0
        if block != report:
            args.doc.write_bytes((head + report + tail).encode("utf-8"))
    except (OSError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
