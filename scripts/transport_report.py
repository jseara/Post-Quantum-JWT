"""Generate RECOMMENDATIONS.md's comparison tables from committed results (S3-03).

S3-03 publishes Sprint 3's end-to-end and mitigation results without recording a new run. This
script reads the committed result files listed in SOURCES, and nothing else: Sprint 1's
summary.json and run.json from WSL2 and macOS, three Sprint 2 sweep.json files from WSL2, and
the macOS S3-01 load.json and S3-02 claims.json, cookies.json, and refs.json. From them it
builds eight Markdown comparison tables: the sources, Sprint 1's sign and verify times, S3-01's
end-to-end latency and throughput, the size limits at the documented defaults (measured on
macOS) and against Sprint 2's boundaries (derived from the WSL2 sweeps), each mitigation's
latency and throughput, and the calculated network cost.

The tables go between two marker lines in RECOMMENDATIONS.md, so the document can be checked
against, and regenerated from, a clean checkout. It needs only the standard library: no stack,
browser, or network.

    python scripts/transport_report.py            print the generated block
    python scripts/transport_report.py --check    exit 1 if the document's block is out of date
    python scripts/transport_report.py --write    replace the document's block

To point the tables at newer runs, edit SOURCES and run --write.
"""

