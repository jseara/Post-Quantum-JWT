# --- Formatting --------------------------------------------------------------------------------


def count(n: int) -> str:
    """Bytes or a count, with thousands separators."""
    return f"{n:,}"


def signed(n: int) -> str:
    """Signed bytes or headroom, with thousands separators."""
    return f"{n:+,}"


def ms(x: float) -> str:
    """An absolute time in milliseconds."""
    return f"{x:.3f}"


def ms_change(x: float) -> str:
    """A difference in milliseconds."""
    return f"{x:+.3f}"


def rps(x: float) -> str:
    """A throughput in requests per second."""
    return f"{x:,.0f}"


def date(stamp: str) -> str:
    """An ISO timestamp to the minute, for example 2026-11-17 03:54."""
    return stamp[:16].replace("T", " ")


def commit(sha: str | None) -> str:
    """A git commit's first 7 characters in backticks, or a dash."""
    return f"`{sha[:7]}`" if sha else DASH


def client(name: str) -> str:
    """The client's display name."""
    return CLIENTS.get(name, name)


def outcome(entry: dict | None) -> str:
    """A size-limit outcome: verified, rejected by a layer, or a dash when there is none."""
    if entry is None:
        return DASH
    if entry["outcome"] == "verified":
        return "verified"
    return f"rejected by {entry['rejected_by']}" if entry.get("rejected_by") else "rejected"


def or_dash(value, formatter) -> str:
    """formatter(value), or a dash for a missing value."""
    return DASH if value is None else formatter(value)


def link(path: str, text: str | None = None) -> str:
    """A Markdown link to a repository-relative path, named after its file by default."""
    return f"[{text or PurePosixPath(path).name}]({path})"


def platform_name(environment: dict | None, directory: str) -> str:
    """macOS or WSL2, from the recorded platform, or from the run directory when there is none
    (the Sprint 2 sweeps record no environment)."""
    name = (environment or {}).get("platform") or ""
    if name.startswith("macOS"):
        return "macOS"
    if "WSL2" in name:
        return "WSL2"
    if not name:
        for part in PurePosixPath(directory).parts:
            if part.endswith("-wsl2"):
                return "WSL2"
            if part.endswith("-macos"):
                return "macOS"
    return name.split("-", 1)[0] or DASH


def run_label(directory: str) -> str:
    """A run directory below results/ and its group, for example 20261117T035444Z-macos."""
    parts = PurePosixPath(directory).parts[1:]
    if parts and parts[0] in RESULT_GROUPS:
        parts = parts[1:]
    return "/".join(parts)


def row_line(cells: Sequence[str]) -> str:
    """One pipe-table row."""
    return "| " + " | ".join(cells) + " |"


def table(columns: Sequence[tuple[str, bool]], rows: Sequence[Sequence[str]]) -> str:
    """A GitHub pipe table; columns are (header, right-aligned) pairs."""
    lines = [row_line([name for name, _ in columns]),
             row_line(["---:" if right else "---" for _, right in columns])]
    lines += [row_line(row) for row in rows]
    return "\n".join(lines)


def section(heading: str, paragraph: str, columns: Sequence[tuple[str, bool]],
            rows: Sequence[Sequence[str]]) -> str:
    """A level-3 section: heading, source paragraph, and table."""
    return f"### {heading}\n\n{paragraph}\n\n{table(columns, rows)}"


def by_key(entries: Sequence[dict], *keys: str) -> dict:
    """Index entries by the values of keys."""
    return {tuple(entry[key] for key in keys): entry for entry in entries}


def flags(settings: dict) -> str:
    """The stack options a run's settings record, as backticked command-line flags."""
    names = (("header_buffers", "--header-buffers"), ("proxy_buffers", "--proxy-buffers"),
             ("upstream_keepalive", "--upstream-keepalive"))
    return ", ".join(f"`{flag} {settings[key]}`" for key, flag in names
                     if settings.get(key) is not None)


# --- Inputs ------------------------------------------------------------------------------------


def read_sources(root: Path) -> dict[str, object]:
    """Parse every file in SOURCES below root; a missing or invalid file raises ValueError."""
    data = {}
    for name in SOURCES:
        try:
            data[name] = json.loads((root / name).read_text(encoding="utf-8"))
        except OSError as error:
            raise ValueError(f"cannot read {name}: {error.strerror or error}") from None
        except ValueError as error:  # JSONDecodeError, or bytes that are not UTF-8.
            raise ValueError(f"{name} is not valid JSON: {error}") from None
        if not isinstance(data[name], dict):
            raise ValueError(f"{name} is not a JSON object")
    return data


