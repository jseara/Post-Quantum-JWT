"""Embed the committed results in the test page, for its read-only mode.

The test page (transport/static/index.html) sends real requests when the transport stack serves
it. Anywhere else, such as GitHub Pages or a file opened from disk, it has no stack behind it,
so it switches to a read-only mode: its buttons replay what the committed runs recorded, and it
shows the comparison tables. This script builds the data that mode reads, from committed result
files only:

- each configuration's natural token (minimal claims, no padding) in Sprint 2's cookie-default
  and bearer-default sweeps (HTTP/1.1, WSL2): the status codes, the verdict, the rejecting
  layer, and the log evidence;
- Sprint 1's sign and verify medians on macOS and WSL2;
- the largest token each carrier verified over HTTP/1.1 (Sprint 2, WSL2) and over HTTPS and
  HTTP/2 (S3-04, macOS);
- results/RECOMMENDATIONS.md's eight comparison tables, from scripts/transport_report.py, plus a table of
  S3-04's limits by protocol.

The data goes into the page as JSON between two marker lines, so the page stays one file that
makes no request on load, and the block can be checked against a clean checkout. It needs only
the standard library: no stack, browser, or network.

    python scripts/transport_pages.py            print the generated block
    python scripts/transport_pages.py --check    exit 1 if the page's block is out of date
    python scripts/transport_pages.py --write    replace the page's block
"""

import argparse
from collections.abc import Sequence
import json
from pathlib import Path
import re
import sys

if __package__ in (None, ""):  # Allow `python scripts/<name>.py` as well as package imports.
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from scripts import transport_report as report


REPO = report.REPO
PAGE = REPO / "transport" / "static" / "index.html"
BEGIN_MARKER = ("<!-- BEGIN generated by scripts/transport_pages.py; "
                "edit the script, not this block -->")
END_MARKER = "<!-- END generated by scripts/transport_pages.py -->"
SCRIPT_ID = "recorded"

# The committed runs the page replays, as repository-relative POSIX paths.
COOKIE_SWEEP = report.COOKIE_DEFAULT
BEARER_SWEEP = report.BEARER_DEFAULT
PROTOCOLS_RUN = "results/transport/20261119T170351Z-macos"
PROTOCOLS = f"{PROTOCOLS_RUN}/protocols.json"
BENCHMARKS = {"macos": report.MACOS_SUMMARY, "wsl2": report.WSL2_SUMMARY}
SOURCES = (COOKIE_SWEEP, BEARER_SWEEP, PROTOCOLS, *BENCHMARKS.values())
REPLAY_LABEL = "Sprint 2, WSL2, HTTP/1.1"  # Where COOKIE_SWEEP and BEARER_SWEEP were recorded.

# The layer names the results record, as the page names them.
LAYERS = {"browser": "Chromium", "proxy": "nginx", "app_server": "waitress",
          "application": "the application"}
PROTOCOL_NAMES = (("http1", "HTTP/1.1"), ("https", "HTTPS"), ("h2", "HTTP/2"))


def read_json(root: Path, name: str) -> dict:
    """Parse one committed file; a missing or invalid file raises ValueError."""
    try:
        data = json.loads((root / name).read_text(encoding="utf-8"))
    except OSError as error:
        raise ValueError(f"cannot read {name}: {error.strerror or error}") from None
    except ValueError as error:
        raise ValueError(f"{name} is not valid JSON: {error}") from None
    if not isinstance(data, dict):
        raise ValueError(f"{name} is not a JSON object")
    return data


def natural_probe(result: dict, sweep: str) -> dict:
    """The probe that sent a configuration's unpadded token, from Chromium."""
    probes = [probe for probe in result["probes"]
              if probe["pad"] == 0 and probe.get("client", "browser") == "browser"]
    if len(probes) != 1:
        raise ValueError(f"{sweep} has {len(probes)} unpadded Chromium probes for "
                         f"{result['algorithm']}, not 1")
    return probes[0]


def replay(probe: dict, run: str) -> dict:
    """What the page shows for one recorded probe."""
    return {"run": run, "label": REPLAY_LABEL, "token_bytes": probe["token_bytes"],
            "outcome": probe["outcome"],
            "rejected_by": LAYERS.get(probe["rejected_by"], probe["rejected_by"]),
            "issue_status": probe["issue_status"], "verify_status": probe["verify_status"],
            "cookie_stored": probe.get("cookie_stored"), "evidence": probe["evidence"]}


def limit(entry: dict | None) -> dict | None:
    """The largest verified token and the first rejection of one sweep, or None."""
    if entry is None:
        return None
    first = entry["first_rejection"]
    return {"largest_verified": entry["largest_verified_token_bytes"],
            "first_rejected": first and first["token_bytes"],
            "rejected_by": first and LAYERS.get(first["rejected_by"], first["rejected_by"])}


def browser_results(sweep: dict) -> dict:
    """A sweep's results from Chromium, by configuration."""
    return {result["algorithm"]: result for result in sweep["results"]
            if result.get("client", "browser") == "browser"}


def protocol_limits(protocols: dict, cookie: dict, bearer: dict, name: str) -> dict:
    """One configuration's limits per carrier over HTTP/1.1, HTTPS, and HTTP/2."""
    compared = report.by_key(protocols["comparison"], "sweep", "algorithm", "client")
    limits = {}
    for carrier, sweep, http1 in (("cookie", "cookie-default", cookie[name]),
                                  ("bearer", "bearer-default", bearer[name])):
        entry = compared.get((sweep, name, "browser"))
        measured = entry["measured"] if entry else {}
        limits[carrier] = {"http1": limit(http1), "https": limit(measured.get("https")),
                           "h2": limit(measured.get("h2"))}
    return limits


def algorithms(data: dict) -> list[dict]:
    """Per configuration: token size, sign and verify medians, replays, and limits."""
    cookie, bearer = browser_results(data[COOKIE_SWEEP]), browser_results(data[BEARER_SWEEP])
    benchmarks = {platform: {entry["algorithm"]: entry for entry in data[path]["algorithms"]}
                  for platform, path in BENCHMARKS.items()}
    rows = []
    for name in data[COOKIE_SWEEP]["settings"]["algorithms"]:
        timing = {platform: {"sign_ms": entries[name]["sign"]["median_ms"],
                             "verify_ms": entries[name]["verify"]["median_ms"]}
                  for platform, entries in benchmarks.items()}
        rows.append({
            "name": name,
            "token_bytes": cookie[name]["smallest_token_bytes"],
            "timing": timing,
            "cookie": replay(natural_probe(cookie[name], COOKIE_SWEEP), COOKIE_SWEEP),
            "bearer": replay(natural_probe(bearer[name], BEARER_SWEEP), BEARER_SWEEP),
            "limits": protocol_limits(data[PROTOCOLS], cookie, bearer, name),
        })
    return rows


def size_cell(entry: dict | None) -> str:
    """One protocol's limit as a table cell."""
    if entry is None:
        return report.DASH
    if entry["largest_verified"] is None:
        return f"none: {entry['rejected_by']} rejects {report.count(entry['first_rejected'])}"
    then = f", then {entry['rejected_by']}" if entry["rejected_by"] else ""
    return f"{report.count(entry['largest_verified'])}{then}"


def protocols_section(rows: list[dict]) -> dict:
    """S3-04's limits by protocol, as one more table."""
    paragraph = (
        "The largest token, in bytes, that Chromium got verified with minimal claims at the "
        "documented default limits, then the layer that rejected the next size. HTTP/1.1 is "
        f"Sprint 2's WSL2 baseline ({report.link(COOKIE_SWEEP, 'cookie-default sweep.json')}, "
        f"{report.link(BEARER_SWEEP, 'bearer-default sweep.json')}); HTTPS and HTTP/2 are "
        f"S3-04's macOS run ({report.link(PROTOCOLS)}). The cookie limits differ by platform "
        "(nginx's 4 KiB response buffer on WSL2, Chromium's 4,096-byte cookie on macOS). Over "
        "HTTP/2, nginx counts the HPACK-compressed header size, so the Bearer limit shifts by a "
        "few bytes from run to run.")
    columns = [["Configuration", False], ["Carrier", False],
               *[[name, False] for _, name in PROTOCOL_NAMES]]
    cells = [[row["name"], carrier_name,
              *[size_cell(row["limits"][carrier][key]) for key, _ in PROTOCOL_NAMES]]
             for row in rows for carrier, carrier_name in report.CARRIERS]
    return {"heading": "Size limits by protocol (S3-04)", "paragraph": paragraph,
            "columns": columns, "rows": cells}


def split_cells(line: str) -> list[str]:
    """The cells of one pipe-table row that transport_report.row_line wrote."""
    if not (line.startswith("| ") and line.endswith(" |")):
        raise ValueError(f"not a table row: {line!r}")
    return line[2:-2].split(" | ")


def report_sections(markdown: str) -> list[dict]:
    """transport_report's generated block, as headings, paragraphs, and table cells."""
    sections = []
    for chunk in re.split(r"^### ", markdown, flags=re.MULTILINE)[1:]:
        heading, paragraph, table = chunk.strip("\n").split("\n\n")
        header, alignment, *rows = table.split("\n")
        columns = [[name, align == "---:"]
                   for name, align in zip(split_cells(header), split_cells(alignment),
                                          strict=True)]
        sections.append({"heading": heading, "paragraph": paragraph, "columns": columns,
                         "rows": [split_cells(row) for row in rows]})
    return sections


def recorded_data(root: Path = REPO) -> dict:
    """Everything the page's read-only mode shows. Reads only committed files below root."""
    root = Path(root)
    data = {name: read_json(root, name) for name in SOURCES}
    try:
        rows = algorithms(data)
    except (AttributeError, IndexError, KeyError, TypeError, ValueError) as error:
        raise ValueError(f"unexpected content in {', '.join(SOURCES)}: {error!r}") from None
    return {
        "generated_by": "scripts/transport_pages.py",
        "runs": {"cookie": COOKIE_SWEEP, "bearer": BEARER_SWEEP, "protocols": PROTOCOLS,
                 "benchmarks": BENCHMARKS},
        "algorithms": rows,
        "sections": [*report_sections(report.report_markdown(root)), protocols_section(rows)],
    }


def page_block(root: Path = REPO) -> str:
    """The generated lines that go between the page's marker lines."""
    text = json.dumps(recorded_data(root), indent=1, ensure_ascii=False)
    # Inside <script>, "</script" or "<!--" in a string would end or change the element.
    text = text.replace("<", "\\u003c")
    return f'<script type="application/json" id="{SCRIPT_ID}">\n{text}\n</script>\n'


def split_page(text: str, name: str) -> tuple[str, str, str]:
    """The text through the BEGIN_MARKER line, the generated block, and the END_MARKER line on.

    Raises ValueError unless there is exactly one BEGIN_MARKER line and, after it, exactly one
    END_MARKER line.
    """
    lines = text.splitlines(keepends=True)
    begins = [index for index, line in enumerate(lines) if line.strip() == BEGIN_MARKER]
    ends = [index for index, line in enumerate(lines) if line.strip() == END_MARKER]
    if len(begins) != 1 or len(ends) != 1 or ends[0] < begins[0]:
        raise ValueError(f"{name} needs exactly one line {BEGIN_MARKER} followed later by "
                         f"exactly one line {END_MARKER}")
    begin, end = begins[0], ends[0]
    return "".join(lines[:begin + 1]), "".join(lines[begin + 1:end]), "".join(lines[end:])


def main(argv: Sequence[str] | None = None) -> int:
    """Print the generated block, or --check or --write it in the page.

    Returns 0 on success, 1 when --check finds the block out of date or a source or the page
    cannot be read, and leaves argparse to exit 2 on a usage error.
    """
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true",
                      help="exit 1 if the page's generated block is out of date")
    mode.add_argument("--write", action="store_true",
                      help="replace the page's generated block, leaving the rest unchanged")
    parser.add_argument("--page", type=Path, default=PAGE,
                        help="the page with the marker lines (default: transport/static/index.html)")
    args = parser.parse_args(argv)

    try:
        if not (args.check or args.write):
            sys.stdout.write(page_block(REPO))
            return 0
        # Both the page and the sources are read before anything is written.
        head, block, tail = split_page(report.read_doc(args.page), str(args.page))
        generated = page_block(REPO)
        if args.check:
            if block != generated:
                print(f"{args.page} is out of date: its generated block differs from the "
                      "committed results; run scripts/transport_pages.py --write",
                      file=sys.stderr)
                return 1
            return 0
        if block != generated:
            args.page.write_bytes((head + generated + tail).encode("utf-8"))
    except (OSError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
