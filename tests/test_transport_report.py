def header(*columns: str) -> str:
    """A Markdown table header row."""
    return "| " + " | ".join(columns) + " |"


def count(number: int) -> str:
    """Bytes and counts."""
    return f"{number:,}"


def signed(number: int) -> str:
    """Signed bytes and headroom."""
    return f"{number:+,}"


def ms(value: float) -> str:
    """Absolute milliseconds."""
    return f"{value:.3f}"


def diff(value: float) -> str:
    """Differences in milliseconds."""
    return f"{value:+.3f}"


def rps(value: float) -> str:
    """Throughput."""
    return f"{value:,.0f}"


def utc(text: str) -> str:
    """A recorded ISO timestamp shown to the minute."""
    return text[:16].replace("T", " ")


def commit_cell(text: str) -> str:
    """A git commit shown as its first 7 characters."""
    return f"`{text[:7]}`"


def outcome(result: dict | None) -> str:
    """A size-limit result: verified, rejected by a layer, or the dash when it is missing."""
    if result is None:
        return DASH
    if result["outcome"] == "verified":
        return "verified"
    return f"rejected by {result['rejected_by']}" if result.get("rejected_by") else "rejected"


def find(entries: list[dict], **fields) -> dict | None:
    """The first entry whose fields match."""
    return next((entry for entry in entries
                 if all(entry.get(key) == value for key, value in fields.items())), None)


def platform_name(environment: dict | None) -> str:
    """'macOS' or 'WSL2' from a recorded environment; a sweep (no environment) is WSL2."""
    if not environment:
        return "WSL2"
    if environment["platform"].startswith("macOS"):
        return "macOS"
    return "WSL2" if "WSL2" in environment["platform"] else environment["platform"]


