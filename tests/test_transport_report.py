def modeled_cells(entry: dict, key: str, sign: int) -> list[str]:
    """One entry's modeled values, matched to load.json's profiles by uplink and RTT."""
    by_profile = {(model["uplink_mbps"], model["rtt_ms"]): model for model in entry["modeled"]}
    cells = []
    for profile in data(LOAD)["network_model"]["profiles"]:
        model = by_profile.get((profile["uplink_mbps"], profile["rtt_ms"]))
        cells.append(DASH if model is None else diff(sign * model[key]))
    return cells


def expected_network() -> list[list[str]]:
    """R12's rows: four groups of six."""
    rows = []
    load_rows = {row["algorithm"]: row for row in data(LOAD)["network_model"]["rows"]}
    reference = load_rows["ES256"]["request_bytes"]
    for name in configuration_order():
        row = load_rows[name]
        rows.append(["Token vs ES256 (S3-01)", name,
                     f"{count(reference)}{ARROW}{count(row['request_bytes'])}",
                     signed(row["extra_request_bytes"]),
                     *modeled_cells(row, "difference_ms", 1)])
    groups = (("Essential vs OIDC claims", CLAIMS, ("oidc", "essential"), "saved_bytes",
               "saved_ms", -1),
              ("Split vs single cookie", COOKIES, ("cookie", "split"), "extra_bytes",
               "extra_ms", 1),
              ("Reference vs Bearer JWT", REFS, ("jwt", "ref"), "saved_bytes", "saved_ms", -1))
    for change, path, (before, after), bytes_key, ms_key, sign in groups:
        by_name = {row["algorithm"]: row for row in data(path)["latency"]["network_model"]}
        for name in configuration_order():
            row = by_name[name]
            rows.append([change, name,
                         f"{count(row['request_bytes'][before])}{ARROW}"
                         f"{count(row['request_bytes'][after])}",
                         signed(sign * row[bytes_key]), *modeled_cells(row, ms_key, sign)])
    return rows


