        added = status
        if before is not None:
            old = set(self.parts(before)[1])
            added = "\n".join(line for line in self.parts(read_text(README))[1]
                              if line not in old)
        for term in ("](RECOMMENDATIONS.md", "S3-03", "scripts/transport_report.py"):
            with self.subTest(term=term):
                self.assertIn(term, added)

