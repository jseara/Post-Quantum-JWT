def read_text(path: Path) -> str:
    """A text file's contents, or "" when it cannot be read."""
    try:
        return path.read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def require_file(path: Path) -> bytes:
    """A file's bytes, failing the calling test when it is missing."""
    if not path.is_file():
        raise AssertionError(f"{path.relative_to(REPO).as_posix()} is missing")
    return path.read_bytes()


_DATA: dict[str, dict] = {}


def data(path: str) -> dict:
    """A committed JSON file, by its repository-relative path."""
    if path not in _DATA:
        _DATA[path] = json.loads((REPO / path).read_text(encoding="utf-8"))
    return _DATA[path]


def copy_sources(root: Path, skip: str | None = None) -> None:
    """Copy every SOURCES file except skip into root, at the same relative paths."""
    for path in SOURCES:
        if path != skip:
            target = root / path
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(REPO / path, target)


def scratch_repo(root: Path, skip: str | None = None, corrupt: str | None = None) -> Path:
    """A copy of the script, its sources (without skip, with corrupt not valid JSON), and the
    document, laid out like the repository so that the copy's REPO is root."""
    require_file(SCRIPT)
    (root / "scripts").mkdir(parents=True)
    shutil.copyfile(SCRIPT, root / "scripts" / "transport_report.py")
    copy_sources(root, skip)
    if corrupt:
        (root / corrupt).write_text('{"truncated": ', encoding="utf-8")
    if DOC.is_file():
        shutil.copyfile(DOC, root / "RECOMMENDATIONS.md")
    return root


def private_names() -> list[str]:
    """This machine's host name and user name, which no output may contain."""
    names = {socket.gethostname(), socket.gethostname().split(".")[0]}
    try:
        names.add(getpass.getuser())
    except (OSError, KeyError):
        pass
    return [name for name in names if len(name) >= 4 and name != "localhost"]


